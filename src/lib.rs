/// Initializes the DDS runtime. Call once before any subscribe/publish/RPC.
///
/// - `domain_id`: DDS domain ID
/// - `network_interface`: network interface to bind (e.g. `"eth0"`, empty = default)
/// - `config_file`: CycloneDDS config file path (empty = default config)
pub fn init_dds(domain_id: i32, network_interface: &str, config_file: &str) {
    ffi::boot_dds(domain_id, network_interface, config_file);
}

// ── Subscribe ──

/// DDS type name of a message type.
///
/// Implemented automatically by the code generator for every message type;
/// you normally don't need to implement it by hand.
pub trait DdsType {
    fn dds_name() -> &'static str;
}

/// Subscription handle: keeps the subscription alive while held, unsubscribes on drop.
pub struct Subscriber {
    id: i32,
}
impl Drop for Subscriber {
    fn drop(&mut self) {
        if self.id > 0 {
            ffi::unsubscribe(self.id);
        }
    }
}

/// Subscribes to a topic and receives the latest message.
///
/// Returns `(Subscriber, watch::Receiver<Option<D>>)`:
/// - holding the `Subscriber` keeps receiving data; dropping it stops the subscription;
/// - the `Receiver` holds the latest message (`None` until the first one arrives);
///   read it with [`watch::Receiver::borrow`].
pub fn subscribe<D: DdsType + DeserializeOwned + Send + Sync + 'static>(
    topic: &str,
) -> (Subscriber, watch::Receiver<Option<D>>) {
    let (tx, rx) = watch::channel(None);
    let id = ffi::subscribe_any(
        topic,
        D::dds_name(),
        Box::new(ByteHandler::new(move |bytes: Vec<u8>| {
            if let Ok(data) = cdr::deserialize::<D>(&bytes[..]) {
                let _ = tx.send_replace(Some(data));
            }
        })),
    );
    (Subscriber { id }, rx)
}

// ── Publish ──

/// Internal publisher interface, implemented by the code generator for every message type.
pub trait TopicPublish {
    type PubFfi: Send + Sync + UniquePtrTarget;
    fn new_publisher(topic: &str) -> anyhow::Result<Arc<UniquePtr<Self::PubFfi>>>;
    fn publish_ffi(pub_: &UniquePtr<Self::PubFfi>, bytes: Vec<u8>);
}

/// Topic publisher.
///
/// Create one with [`Publisher::new`] and publish a message with [`Publisher::publish`].
pub struct Publisher<T: TopicPublish>
where
    T::PubFfi: UniquePtrTarget,
{
    inner: Arc<UniquePtr<T::PubFfi>>,
}

impl<T: TopicPublish> Publisher<T>
where
    T::PubFfi: UniquePtrTarget,
{
    /// Creates a publisher for the given topic.
    pub fn new(topic: &str) -> anyhow::Result<Self> {
        Ok(Self {
            inner: T::new_publisher(topic)?,
        })
    }

    /// Publishes one message (type `T`).
    pub fn publish(&self, d: &T)
    where
        T: Serialize,
    {
        if let Ok(bytes) = cdr::serialize::<_, _, cdr::CdrLe>(d, cdr::Infinite) {
            T::publish_ffi(&self.inner, bytes);
        }
    }
}

// Generates the publisher implementation for each message type (invoked by build.rs)
macro_rules! topic_publish {
    ($rust:ty, $ffi_pub:ident, $new_fn:ident, $publish_fn:ident) => {
        unsafe impl Send for ffi::$ffi_pub {}
        unsafe impl Sync for ffi::$ffi_pub {}
        impl TopicPublish for $rust {
            type PubFfi = ffi::$ffi_pub;
            fn new_publisher(topic: &str) -> anyhow::Result<Arc<UniquePtr<Self::PubFfi>>> {
                let inner = ffi::$new_fn(topic);
                if inner.is_null() {
                    anyhow::bail!("failed to create publisher for {}", stringify!($rust));
                }
                Ok(Arc::new(inner))
            }
            fn publish_ffi(pub_: &UniquePtr<Self::PubFfi>, bytes: Vec<u8>) {
                ffi::$publish_fn(pub_, bytes);
            }
        }
    };
}

